local helpers = require("helpers")

describe("Outbox", function()
  local Outbox

  before_each(function()
    Outbox = helpers.loadAddonFile("src/core/Outbox.lua", {})
  end)

  it("is empty at first", function()
    local box = Outbox.new()
    assert.is_nil(box:pop(0))
    assert.are.equal(0, box:size())
    assert.are.equal(0.2, box.interval)
  end)

  it("sends in order, at most one chunk per interval", function()
    local box = Outbox.new(0.2)
    box:push(5, "a")
    box:push(6, "b")
    box:push(5, "c")
    assert.are.same({ 5, "a" }, { box:pop(10) })
    local target, wait = box:pop(10.1)
    assert.is_nil(target)
    assert.is_true(math.abs(wait - 0.1) < 1e-9)
    assert.is_true(math.abs(box:wait(10.1) - 0.1) < 1e-9)
    assert.are.same({ 6, "b" }, { box:pop(10.2) })
    assert.are.same({ 5, "c" }, { box:pop(10.5) })
    assert.is_nil(box:pop(11))
    assert.are.equal(0, box:size())
  end)

  it("reports no wait before the first send and after a long pause", function()
    local box = Outbox.new(0.2)
    assert.are.equal(0, box:wait(0))
    box:push(1, "x")
    box:pop(0)
    assert.are.equal(0, box:wait(5))
  end)

  it("keeps working after being drained", function()
    local box = Outbox.new(0.5)
    box:push(1, "x")
    box:pop(0)
    box:pop(1)
    box:push(2, "y")
    assert.are.equal(1, box:size())
    assert.are.same({ 2, "y" }, { box:pop(1) })
  end)
end)
